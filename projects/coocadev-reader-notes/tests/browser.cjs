const fs=require('node:fs'), path=require('node:path');
const {chromium}=require('C:/Users/kokak/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fixture=JSON.parse(fs.readFileSync(path.join(__dirname,'.runtime-fixture.json'),'utf8'));
const report={checks:[],errors:[]};
const check=(pass,name)=>report.checks.push({name,pass:!!pass});
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 const context=await browser.newContext({viewport:{width:1280,height:900}});
 const page=await context.newPage();
 page.on('pageerror',error=>report.errors.push(error.stack));
 await page.goto(fixture.base+'/wp-login.php');
 await page.locator('#user_login').fill(fixture.a.login);
 await page.locator('#user_pass').fill(fixture.a.password);
	await page.locator('[name="redirect_to"]').evaluate((element,url)=>{element.value=url;},fixture.base+'/?p='+fixture.post);
 await Promise.all([page.waitForURL(url=>!url.pathname.includes('wp-login')),page.locator('#wp-submit').click()]);
 await page.goto(fixture.base+'/?p='+fixture.post);
 await page.locator('.ccrn-shell textarea').first().waitFor();
 check(await page.locator('.ccrn-shell textarea').count()===2,'Two note blocks become working editors');
 const text='Browser autosave '+Date.now()+' <script>window.CCRN_XSS=1</script> 😀';
 await page.locator('.ccrn-shell textarea').first().fill(text);
 await page.waitForFunction(text=>[...document.querySelectorAll('.ccrn-shell textarea')].every(e=>e.value===text),text);
 check(true,'Duplicate note instances share draft immediately');
 await page.waitForFunction(()=>[...document.querySelectorAll('.ccrn-status')].every(e=>e.textContent==='Saved'));
 await page.reload();
 await page.locator('.ccrn-shell textarea').first().waitFor();
 check(await page.locator('.ccrn-shell textarea').first().inputValue()===text,'Autosave survives page reload');
 check(!(await page.evaluate(()=>window.CCRN_XSS)),'Saved markup remains literal, never executes');
 const page2=await context.newPage();
 await page2.goto(fixture.base+'/?p='+fixture.post);
 await page2.locator('.ccrn-shell textarea').first().waitFor();
 await page.locator('.ccrn-shell textarea').first().fill('Fresh tab one '+Date.now());
 await page.waitForFunction(()=>[...document.querySelectorAll('.ccrn-status')].every(e=>e.textContent==='Saved'));
 await page2.locator('.ccrn-shell textarea').first().fill('Stale tab two draft');
 await page2.locator('.ccrn-conflict').first().waitFor();
 check(true,'Concurrent tab edit displays conflict instead of silent overwrite');
 await page2.locator('.ccrn-conflict').first().getByRole('button',{name:'Load saved version'}).click();
 check((await page2.locator('.ccrn-shell textarea').first().inputValue()).startsWith('Fresh tab one'),'Explicit load resolves to saved version');
 const downloadPromise=page2.waitForEvent('download');
 await page2.getByRole('button',{name:'Export all notes',exact:true}).click();
 const download=await downloadPromise;
 await download.saveAs(path.join(__dirname,'../reports/0.1.0/export-ui.txt'));
 check(fs.readFileSync(path.join(__dirname,'../reports/0.1.0/export-ui.txt'),'utf8').includes('Fresh tab one'),'UI text export includes saved note');
 await page2.evaluate(()=>window.dispatchEvent(new PageTransitionEvent('pagehide',{persisted:true})));
 check(await page2.locator('.ccrn-shell textarea').count()===0,'pagehide synchronously removes private DOM');
 await page2.evaluate(()=>window.dispatchEvent(new PageTransitionEvent('pageshow',{persisted:true})));
 await page2.locator('.ccrn-shell textarea').first().waitFor();
 check(true,'pageshow revalidates and restores private editor');
	await page2.evaluate(()=>window.scrollTo(0,0));
 await page2.screenshot({path:path.join(__dirname,'../reports/0.1.0/reader-notes-desktop.png'),fullPage:true});
 await page2.setViewportSize({width:390,height:844});
 check(await page2.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'390px mobile viewport has no horizontal overflow');
 await page2.screenshot({path:path.join(__dirname,'../reports/0.1.0/reader-notes-mobile.png'),fullPage:true});
 check(report.errors.length===0,'Browser run has no uncaught JS errors');
 report.total=report.checks.length;report.failed=report.checks.filter(x=>!x.pass).length;
 fs.writeFileSync(path.join(__dirname,'../reports/0.1.0/browser.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
 await browser.close();
 if(report.failed)process.exitCode=1;
})().catch(error=>{console.error(error.stack);process.exit(1);});

